local version = ZOI.VERSION or "1.0.3"
local sha512 = "9a055e1008827b9510e9b653834645782ebb7f92b3cd397d6a64bd43314e73856d2237dbc9b8e2d809e363fda96aef919dee4bd79cfe22261ee36bdb73c1e9a0"
-- Upstream publishes no release tarball and does not sign releases, so this
-- is the OpenLDAP GitLab archive of the LMDB_<version> tag. Gentoo has no
-- 1.0.3 entry yet; the hash was computed from the archive, which differs
-- from the 1.0.2 archive (hash matching Gentoo's Manifest) only in CHANGES,
-- lmdb.h, mdb.c and the man pages.

metadata({
	name = "lmdb",
	repo = "core",
	version = version,
	revision = "1",
	debug = { sub_package = true },
	description = "Symas Lightning Memory-Mapped Database",
	website = "https://www.symas.com/mdb",
	license = "OLDAP-2.8",
	maintainer = {
		name = "Zillowe Foundation",
		website = "https://zillowe.qzz.io",
		email = "contact@zillowe.qzz.io",
	},
	author = {
		name = "Symas Corporation and the OpenLDAP Foundation",
		website = "https://www.symas.com/mdb",
	},
	bins = { "mdb_copy", "mdb_drop", "mdb_dump", "mdb_load", "mdb_stat" },
	scope = "system",
	scopes = { "system" },
	platforms = { "linux-amd64" },
	types = { "source" },
	zoios = true,
})

dependencies({
	build = {
		types = {
			source = {
				required = {
					"pacman:base-devel",
					"pacman:curl",
					"pacman:gcc",
					"pacman:make",
					"pacman:tar",
				},
			},
		},
	},
	runtime = {
		required = {
			"zoi:@core/glibc",
		},
	},
})

-- Every shell step runs checked (`set -e`, a failure stops the build) with
-- these variables. `$ROOT` (the staged system root) is always set by cmd().
local opts = { check = true, env = { VER = version, SHA512 = sha512 } }

local srcdir = "openldap-LMDB_" .. version .. "/libraries/liblmdb"

function prepare()
	cmd(
		[[
		# git.openldap.org rate-limits archive downloads (HTTP 429), and CI
		# runs prepare() twice (build, then bundle): back off and retry.
		curl -sSfL --retry 8 --retry-delay 20 --retry-all-errors \
			"https://git.openldap.org/openldap/openldap/-/archive/LMDB_$VER/openldap-LMDB_$VER.tar.gz" \
			-o "openldap-LMDB_$VER.tar.gz"
		echo "$SHA512  openldap-LMDB_$VER.tar.gz" | sha512sum -c -
		tar -xf "openldap-LMDB_$VER.tar.gz"
	]],
		opts
	)
end

function build()
	cmd(
		[[
		cd "openldap-LMDB_$VER/libraries/liblmdb"
		make -j"$(nproc)" OPT="${CFLAGS:--O2 -pipe}" CPPFLAGS="${CPPFLAGS:-}" LDFLAGS="${LDFLAGS:-} -pthread" prefix=/usr
	]],
		opts
	)
end

function package()
	cmd(
		[[
		cd "openldap-LMDB_$VER/libraries/liblmdb"
		install -dm755 "$ROOT"/usr/bin "$ROOT"/usr/lib "$ROOT"/usr/include
		make DESTDIR="$ROOT" prefix=/usr install
		# lmdb.pc is generated by the build but not installed by upstream.
		install -Dm644 lmdb.pc -t "$ROOT/usr/lib/pkgconfig/"
		# Static library: nothing in Zoidberg links it statically.
		rm -f "$ROOT/usr/lib/liblmdb.a"
	]],
		opts
	)
	zlicense(srcdir .. "/LICENSE")
	zlicense(srcdir .. "/COPYRIGHT")
end
